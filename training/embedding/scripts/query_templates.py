JOSA_PAIRS = {  # 자리 이름 -> (받침 있을 때, 없을 때)
    "이가": ("이", "가"), "을를": ("을", "를"), "은는": ("은", "는"), "과와": ("과", "와"),
    "이랑랑": ("이랑", "랑"), "으로": ("으로", "로"),
}


def _last_hangul(word: str):
    for ch in reversed(word.strip()):
        if "가" <= ch <= "힣":
            return ch
        if ch.isalnum():
            return None
    return None


def has_batchim(word: str) -> bool:
    ch = _last_hangul(word)
    return ch is not None and (ord(ch) - 0xAC00) % 28 != 0


def josa(word: str, slot: str) -> str:
    with_b, without_b = JOSA_PAIRS[slot]
    ch = _last_hangul(word)
    if slot == "으로" and ch is not None and (ord(ch) - 0xAC00) % 28 == 8:  # ㄹ 받침은 '로' (예: 오름으로 X, 산골로)
        return word + without_b
    return word + (with_b if has_batchim(word) else without_b)


def join_phrases(phrases: Sequence[str], style: int) -> str:
    """['바다', '섬'] -> '바다랑 섬' / '바다와 섬' / '바다, 섬'. 셋이면 앞 둘은 쉼표."""
    if len(phrases) == 1:
        return phrases[0]
    head, last = list(phrases[:-1]), phrases[-1]
    if style == 0:
        return ", ".join(head[:-1] + [josa(head[-1], "이랑랑")]) + " " + last
    if style == 1:
        return ", ".join(head[:-1] + [josa(head[-1], "과와")]) + " " + last
    return ", ".join(list(phrases))


def render(template: str, phrases: Sequence[str], join_style: int, region_loc: str, region_adn: str,
           fluff: str, head: str) -> str:
    k = join_phrases(phrases, join_style)
    values = {
        "K": k, "RL": region_loc, "RA": region_adn, "F": fluff, "H": head,
        **{f"K_{slot}": josa(k, slot) for slot in JOSA_PAIRS},
        **{f"H_{slot}": josa(head, slot) for slot in JOSA_PAIRS},
    }
    text = template.format(**values)
    return " ".join(text.split())


